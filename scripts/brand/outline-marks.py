"""Outline the Bruno Simone logotype from Big Shoulders into SVG path data.

Dev-only tool (needs fontTools: `pip install fonttools`). Writes
src/brand/marks.ts with one path per optical size, in font units, y-down,
cap top at y=0 and baseline at y=CAP. Run:

  python scripts/brand/outline-marks.py "<path to BigShoulders[opsz,wght].ttf>"
"""

import json
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

SRC = Path(sys.argv[1])
OUT = Path(__file__).resolve().parents[2] / "src/brand/marks.ts"

# (key, text, opsz, wght, tracking in em)
VERSIONS = [
    ("wordmark", "BRUNO SIMONE", 72, 900, 0.012),
    ("wordmarkSmall", "BRUNO SIMONE", 26, 850, 0.03),
    ("b16", "B", 16, 850, 0),
    ("b32", "B", 29, 850, 0),
    ("b64", "B", 59, 900, 0),
    ("b180", "B", 72, 900, 0),
]


def pair_kerning(font):
    """Collect class/pair kerning (GPOS lookup type 2) into a dict."""
    kern = {}
    if "GPOS" not in font:
        return kern
    gpos = font["GPOS"].table
    lookups = set()
    for rec in gpos.FeatureList.FeatureRecord:
        if rec.FeatureTag == "kern":
            lookups.update(rec.Feature.LookupListIndex)
    for li in lookups:
        lookup = gpos.LookupList.Lookup[li]
        for st in lookup.SubTable:
            if lookup.LookupType == 9:
                st = st.ExtSubTable
            if getattr(st, "LookupType", 2) != 2 and lookup.LookupType not in (2, 9):
                continue
            cov = st.Coverage.glyphs
            if st.Format == 1:
                for i, first in enumerate(cov):
                    for pvr in st.PairSet[i].PairValueRecord:
                        v = pvr.Value1.XAdvance if pvr.Value1 and hasattr(pvr.Value1, "XAdvance") else 0
                        kern.setdefault((first, pvr.SecondGlyph), v or 0)
            elif st.Format == 2:
                c1 = st.ClassDef1.classDefs
                c2 = st.ClassDef2.classDefs
                for first in cov:
                    k1 = c1.get(first, 0)
                    row = st.Class1Record[k1].Class2Record
                    for second, k2 in list(c2.items()):
                        v = row[k2].Value1
                        x = getattr(v, "XAdvance", 0) if v else 0
                        if x:
                            kern.setdefault((first, second), x)
    return kern


def outline(text, opsz, wght, tracking):
    font = TTFont(SRC)
    inst = instantiateVariableFont(font, {"opsz": opsz, "wght": wght})
    upm = inst["head"].unitsPerEm
    cap = inst["OS/2"].sCapHeight
    cmap = inst.getBestCmap()
    gs = inst.getGlyphSet()
    hmtx = inst["hmtx"]
    kern = pair_kerning(inst)
    pen = SVGPathPen(gs, ntos=lambda v: (f"{v:.1f}").rstrip("0").rstrip("."))
    x = 0
    names = [cmap[ord(c)] for c in text]
    xmin = None
    for i, name in enumerate(names):
        adv, lsb = hmtx[name]
        if name != "space" and ord(text[i]) != 32:
            # flip y: font y-up → svg y-down with baseline at y=cap
            tp = TransformPen(pen, (1, 0, 0, -1, x, cap))
            gs[name].draw(tp)
            xmin = x + lsb if xmin is None else xmin
        x += adv + tracking * upm
        if i + 1 < len(names):
            x += kern.get((name, names[i + 1]), 0)
    width = x - tracking * upm  # no trailing tracking
    return {
        "d": pen.getCommands(),
        "upm": upm,
        "cap": cap,
        "width": round(width),
        "inkLeft": xmin or 0,
    }


def main():
    marks = {key: outline(t, o, w, tr) for key, t, o, w, tr in VERSIONS}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(marks, indent=2)
    OUT.write_text(
        "// Generated by scripts/brand/outline-marks.py from Big Shoulders (OFL).\n"
        "// Font units, y-down: cap top at y=0, baseline at y=cap. Do not edit by hand.\n\n"
        "export type MarkOutline = { d: string; upm: number; cap: number; width: number; inkLeft: number };\n\n"
        f"export const marks = {body} as const satisfies Record<string, MarkOutline>;\n"
    )
    for k, m in marks.items():
        print(k, "width", m["width"], "cap", m["cap"], "chars", len(m["d"]))


main()
